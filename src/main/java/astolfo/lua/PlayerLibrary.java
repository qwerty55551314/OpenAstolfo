   private static double[] computeStrafeMotion(double d) {
      float f = mc.thePlayer.movementInput.moveForward;
      float f1 = mc.thePlayer.movementInput.moveStrafe;
      float f2 = mc.thePlayer.rotationYaw;
      float f3 = f1 * f1 + f * f;
      if (f3 >= 1.0E-4F) {
         f3 = MathHelper.sqrt_float(f3);
         if (f3 < 1.0F) {
            f3 = 1.0F;
         }

         f3 = 1.0F / f3;
         f1 *= f3;
         f *= f3;
         float f4 = MathHelper.sin(mc.thePlayer.rotationYaw * (float) Math.PI / 180.0F);
         float f5 = MathHelper.cos(mc.thePlayer.rotationYaw * (float) Math.PI / 180.0F);
         double d0 = (double)f1 * d * (double)f5 - (double)f * d * (double)f4;
         double d1 = (double)f * d * (double)f5 + (double)f1 * d * (double)f4;
         return new double[]{d0, d1};
      } else {
         return null;
      }
   }

